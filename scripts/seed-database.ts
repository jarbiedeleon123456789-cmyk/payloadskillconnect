async function seed() {
  const payload = await getPayload({ config })

  for (const collection of [
    'works',
    'certificates',
    'requests',
    'announcements',
    'users',
  ] as const) {
    await payload.delete({ collection, where: {}, overrideAccess: true })
  }

  const userIds = new Map<string, string | number>()
  for (const [
    id,
    role,
    name,
    email,
    barangay,
    phone,
    lat,
    lng,
    skillCategory,
    verified,
    rating,
    ratingCount,
    jobs,
    availability,
    bio,
    rateMin,
    rateMax,
  ] of users) {
    const created = await payload.create({
      collection: 'users',
      overrideAccess: true,
      data: {
        role,
        name,
        email,
        password,
        barangay,
        phone,
        lat,
        lng,
        skillCategory,
        verified,
        rating,
        ratingCount,
        jobs,
        availability,
        bio,
        rateMin,
        rateMax,
      } as any,
    })
    userIds.set(id, created.id)
    if (role === 'worker' && verified) {
      await payload.update({
        collection: 'users',
        id: created.id,
        overrideAccess: true,
        data: { verified: true } as any,
      })
    }
  }
  for (const [id, category, dateLabel, title, body, sortOrder] of announcements) {
    await payload.create({
      collection: 'announcements',
      overrideAccess: true,
      data: { id, category, dateLabel, title, body, sortOrder } as any,
    })
  }
  for (const [id, worker, title, issuer, year] of certificates) {
    await payload.create({
      collection: 'certificates',
      overrideAccess: true,
      data: { worker: userIds.get(worker), title, issuer, year } as any,
    })
  }
  for (const [id, worker, caption] of works) {
    await payload.create({
      collection: 'works',
      overrideAccess: true,
      data: { worker: userIds.get(worker), caption } as any,
    })
  }
  for (const [
    id,
    ticketId,
    customer,
    customerName,
    barangay,
    contactNumber,
    skillNeeded,
    description,
    preferredDate,
    status,
    worker,
    workerName,
    rating,
    lat,
    lng,
  ] of requests) {
    await payload.create({
      collection: 'requests',
      overrideAccess: true,
      data: {
        ticketId,
        customer: userIds.get(customer),
        customerName,
        barangay,
        contactNumber,
        skillNeeded,
        description,
        preferredDate,
        status,
        worker: worker ? userIds.get(worker) : undefined,
        workerName,
        rating,
        lat,
        lng,
      } as any,
    })
  }

  const counts = await Promise.all(
    ['users', 'announcements', 'certificates', 'works', 'requests'].map(async (collection) => [
      collection,
      (await payload.find({ collection: collection as any, limit: 0, overrideAccess: true }))
        .totalDocs,
    ]),
  )
  console.log('Seed complete:', Object.fromEntries(counts))
  console.log('Imported users use password:', password)
  process.exit(0)
}

